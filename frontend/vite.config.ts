import { fileURLToPath, URL } from "node:url";
import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react"; // keep the import generated by the template
import { defineConfig } from "vite";

export default defineConfig({
  plugins: [react(), tailwindcss()],
  resolve: {
    alias: { "@": fileURLToPath(new URL("./src", import.meta.url)) },
  },
  server: {
    port: 5173,
    proxy: {
      // The browser only talks to localhost:5173 (same origin). Without this, the refresh
      // cookie (SameSite=Lax) set by the API would be rejected as a cross-site cookie.
      "/api": { target: "http://127.0.0.1:8000", changeOrigin: true },
    },
  },
});